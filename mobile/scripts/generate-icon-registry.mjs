import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const iconsDir = path.resolve(__dirname, "../assets/icons");
const outputPath = path.resolve(__dirname, "../src/components/icons/iconRegistry.ts");

function toCamelCase(str) {
  return str
    .replace(/[-_\s]+(.)/g, (_, char) => char.toUpperCase())
    .replace(/^./, (char) => char.toLowerCase());
}

function fileToName(filename) {
  if (filename === "Icon.svg") {
    return "default";
  }

  const iconNumberMatch = filename.match(/^Icon-(\d+)\.svg$/);
  if (iconNumberMatch) {
    return `icon${iconNumberMatch[1]}`;
  }

  if (filename.startsWith("Property 1=")) {
    const value = filename.slice("Property 1=".length, -4).replace(/ \d+$/, "");
    return toCamelCase(value);
  }

  if (filename.startsWith("State=")) {
    return toCamelCase(`state-${filename.slice(6, -4)}`);
  }

  const stripped = filename.replace(/\.svg$/i, "").replace(/^(Icon|icon)-(\d+-)?/i, "");
  if (stripped.toUpperCase() === stripped && stripped.length <= 3) {
    return stripped.toLowerCase();
  }

  return toCamelCase(stripped);
}

function normalizeSvgContent(content) {
  return content
    .replace(/\sstyle="[^"]*fill:[^"]*"/gi, ' fill="currentColor"')
    .replace(/\sstyle="[^"]*"/gi, "")
    .replace(/\sfill="(?!none|currentColor)[^"]*"/gi, ' fill="currentColor"')
    .replace(/\sstroke="(?!none|currentColor)[^"]*"/gi, ' stroke="currentColor"');
}

const files = fs.readdirSync(iconsDir).filter((file) => file.endsWith(".svg")).sort();

for (const file of files) {
  const filePath = path.join(iconsDir, file);
  const content = fs.readFileSync(filePath, "utf8");
  const normalized = normalizeSvgContent(content);

  if (normalized !== content) {
    fs.writeFileSync(filePath, normalized);
  }
}

const entries = files.map((file) => ({
  file,
  name: fileToName(file),
}));

const duplicateNames = entries
  .map((entry) => entry.name)
  .filter((name, index, names) => names.indexOf(name) !== index);

if (duplicateNames.length > 0) {
  throw new Error(`Duplicate icon names: ${duplicateNames.join(", ")}`);
}

const importLines = entries.map(
  (entry, index) => `import IconAsset${index} from "../../../assets/icons/${entry.file}";`,
);

const registryLines = entries.map(
  (entry, index) => `  ${entry.name}: IconAsset${index},`,
);

const nameUnion = entries.map((entry) => `  | "${entry.name}"`).join("\n");

const output = `/* eslint-disable import/no-unresolved */
/* This file is generated by scripts/generate-icon-registry.mjs */

import type { FC } from "react";
import type { SvgProps } from "react-native-svg";

${importLines.join("\n")}

export type IconName =
${nameUnion};

export type IconComponent = FC<SvgProps>;

export const iconRegistry: Record<IconName, IconComponent> = {
${registryLines.join("\n")}
};
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output);
console.log(`Generated ${entries.length} icons -> ${outputPath}`);
