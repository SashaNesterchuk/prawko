#!/usr/bin/env node

import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const repoRoot = new URL("..", import.meta.url).pathname;
const manifestPath = join(repoRoot, "data", "cz-road-signs-dopravni-znaceni-eu", "manifest.json");
const outputPath = join(repoRoot, "mobile", "variants", "czech", "road-sign-assets.ts");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));

const signs = [...manifest.signs].sort((left, right) =>
  left.id.localeCompare(right.id, "cs", { numeric: true })
);

const entries = signs.map(
  (sign) => `  "${sign.id}": require("../../assets/cz-road-signs/dopravni-znaceni-eu/${sign.assetFile}"),`
);

const source = `/* This file is generated by scripts/generate-czech-road-sign-assets.mjs */
import type { ComponentType } from "react";
import type { ImageSourcePropType } from "react-native";
import type { SvgProps } from "react-native-svg";

// This registry is resolved only in APP_VARIANT=czech, so none of these files
// are reachable from a Prawko build.
export const signAssets: Record<string, ComponentType<SvgProps>> = {};

const rasterSignAssets: Record<string, ImageSourcePropType> = {
${entries.join("\n")}
};

export function getSignAssetComponent(signId: string): ComponentType<SvgProps> | undefined {
  return signAssets[signId];
}

export function getSignRasterSource(signId: string): ImageSourcePropType | undefined {
  return rasterSignAssets[signId];
}
`;

await writeFile(outputPath, source);
console.log(`Generated ${signs.length} Czech raster asset registrations.`);
